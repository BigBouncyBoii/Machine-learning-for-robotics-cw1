% CODE MAP of Task1_Whatif_DataAnalysis.m (four-panel plot of the darkening What-if)
%   Read data                     read Task1_Whatif_Results/fruit_detection_data_mirror_False.csv;
%                                 box width, height and area (width x height)
%   Figure size for an A4 report  figure and 2x2 layout size
%   Axes formatting               fonts, grid and line styles shared by all panels
%   Plot each fruit               apple, capsicum, lemon sorted by dark factor: width, height,
%                                 centroid distance and box area against dark factor
%   Panel titles and labels       titles and axis labels of the four panels
%   Axis limits                   x from 1.0 down to 0.1, y limits per panel
%   Shared legend                 one legend for the three fruits
%   Main title                    figure title
%   Extra-large, bold formatting  final text sizes for the report
%   AI use                        GPT-6.1 Sol (setting: medium); GPT-6 Astra (setting: light)

clear;
clc;
close all;

%% Read data
scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptDir);
csvPath = fullfile(scriptDir, "Task1_Whatif_Results", "fruit_detection_data_mirror_False.csv");
T = readtable(csvPath);

T.box_width  = T.x_max - T.x_min;
T.box_height = T.y_max - T.y_min;
% Geometric rectangle area, consistent with the plotted width and height.
T.box_area = T.box_width .* T.box_height;

fruits = ["apple", "capsicum", "lemon"];
fruitLabels = ["Apple", "Capsicum", "Lemon"];

colours = [
    0.80 0.20 0.25
    0.00 0.45 0.70
    0.85 0.60 0.05
];

markers = ["o", "s", "^"];

%% Figure size for an A4 report
% Insert into the report at approximately 18 cm wide
fig = figure( ...
    "Color", "white", ...
    "Units", "centimeters", ...
    "Position", [2 2 18 14.5]);

layout = tiledlayout(fig, 2, 2, ...
    "TileSpacing", "compact", ...
    "Padding", "compact");

ax1 = nexttile(layout, 1);
ax2 = nexttile(layout, 2);
ax3 = nexttile(layout, 3);
ax4 = nexttile(layout, 4);

axesList = [ax1, ax2, ax3, ax4];

%% Axes formatting
for ax = axesList
    hold(ax, "on");

    set(ax, ...
        "FontName", "Arial", ...
        "FontSize", 10, ...
        "FontWeight", "bold", ...
        "LineWidth", 1.0, ...
        "TickDir", "out", ...
        "TickLength", [0.015 0.015], ...
        "Box", "off", ...
        "XDir", "reverse", ...
        "XLim", [0.1 1.0], ...
        "XTick", 0.1:0.1:1.0, ...
        "XMinorTick", "off", ...
        "YGrid", "on", ...
        "XGrid", "on", ...
        "GridAlpha", 0.15, ...
        "Layer", "top");

    xlabel(ax, "Dark factor", ...
        "FontSize", 11, ...
        "FontWeight", "bold");
end

%% Plot each fruit
for k = 1:numel(fruits)

    S = T(string(T.fruit) == fruits(k), :);
    S = sortrows(S, "darkFactor", "descend");

    plot(ax1, S.darkFactor, S.box_width, ...
        "Color", colours(k,:), ...
        "Marker", markers(k), ...
        "LineWidth", 1.8, ...
        "MarkerSize", 4.5, ...
        "MarkerFaceColor", "white", ...
        "DisplayName", fruitLabels(k));

    plot(ax2, S.darkFactor, S.box_height, ...
        "Color", colours(k,:), ...
        "Marker", markers(k), ...
        "LineWidth", 1.8, ...
        "MarkerSize", 4.5, ...
        "MarkerFaceColor", "white", ...
        "DisplayName", fruitLabels(k));

    plot(ax3, S.darkFactor, S.centroid_distance, ...
        "Color", colours(k,:), ...
        "Marker", markers(k), ...
        "LineWidth", 1.8, ...
        "MarkerSize", 4.5, ...
        "MarkerFaceColor", "white", ...
        "DisplayName", fruitLabels(k));

    plot(ax4, S.darkFactor, S.box_area, ...
        "Color", colours(k,:), ...
        "Marker", markers(k), ...
        "LineWidth", 1.8, ...
        "MarkerSize", 4.5, ...
        "MarkerFaceColor", "white", ...
        "DisplayName", fruitLabels(k));
end

%% Panel titles and labels
title(ax1, "(a) Bounding-box width", ...
    "FontSize", 11, ...
    "FontWeight", "bold");

ylabel(ax1, "Width (pixels)", ...
    "FontSize", 11, ...
    "FontWeight", "bold");

title(ax2, "(b) Bounding-box height", ...
    "FontSize", 11, ...
    "FontWeight", "bold");

ylabel(ax2, "Height (pixels)", ...
    "FontSize", 11, ...
    "FontWeight", "bold");

title(ax3, "(c) Distance between centroid methods", ...
    "FontSize", 11, ...
    "FontWeight", "bold");

ylabel(ax3, "Distance (pixels)", ...
    "FontSize", 11, ...
    "FontWeight", "bold");

title(ax4, "(d) Bounding-box area", ...
    "FontSize", 11, "FontWeight", "bold");
ylabel(ax4, "Area (pixels^2)", ...
    "FontSize", 11, "FontWeight", "bold");

%% Axis limits
for ax = axesList
    ylim(ax, "padded");
end

distanceLimits = ylim(ax3);
ylim(ax3, [0 distanceLimits(2)]);

%% Shared legend
lgd = legend(ax3, ...
    "Orientation", "horizontal", ...
    "Box", "off", ...
    "FontName", "Arial", ...
    "FontSize", 10, ...
    "FontWeight", "bold");

lgd.Layout.Tile = "south";

%% Main title
title(layout, "Effect of Darkening on Fruit Detection", ...
    "FontName", "Arial", ...
    "FontSize", 13, ...
    "FontWeight", "bold");

%% Extra-large, bold formatting
set(fig, ...
    "Units", "centimeters", ...
    "Position", [2 2 18 17]);

for ax = axesList
    % Tick labels and axis lines
    set(ax, ...
        "FontSize", 15, ...
        "FontWeight", "bold", ...
        "LineWidth", 1.8, ...
        "XTick", [0.1 0.3 0.5 0.7 0.9 1.0]);

    % Axis labels
    set(ax.XLabel, "FontSize", 17, "FontWeight", "bold");
    set(ax.YLabel, "FontSize", 17, "FontWeight", "bold");

    % Panel titles
    set(ax.Title, "FontSize", 17, "FontWeight", "bold");

    % Curves and markers
    set(findall(ax, "Type", "line"), ...
        "LineWidth", 3, ...
        "MarkerSize", 7);
end

% Shorter titles to accommodate larger text
title(ax1, "(a) Box width", ...
    "FontSize", 17, "FontWeight", "bold");

title(ax2, "(b) Box height", ...
    "FontSize", 17, "FontWeight", "bold");

title(ax3, "(c) Centroid distance", ...
    "FontSize", 17, "FontWeight", "bold");

title(ax4, "(d) Box area", ...
    "FontSize", 17, "FontWeight", "bold");

% Legend
set(lgd, ...
    "FontSize", 16, ...
    "FontWeight", "bold");

% Main title split over two lines
title(layout, ...
    ["Effect of Darkening"; "on Fruit Detection"], ...
    "FontName", "Arial", ...
    "FontSize", 21, ...
    "FontWeight", "bold");

drawnow;